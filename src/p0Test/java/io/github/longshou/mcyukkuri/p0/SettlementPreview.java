package io.github.longshou.mcyukkuri.p0;

import com.google.gson.JsonObject;
import io.github.longshou.mcyukkuri.entity.YukkuriEntity;
import io.github.longshou.mcyukkuri.settlement.SettlementSpawner;
import java.util.List;
import java.util.Map;
import net.minecraft.core.BlockPos;
import net.minecraft.server.MinecraftServer;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.item.ItemEntity;
import net.minecraft.world.level.GameRules;
import net.minecraft.world.level.GameType;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.LeavesBlock;
import net.minecraft.world.phys.AABB;

/** Controlled presentation of the real generator in the isolated p0-preview world. */
final class SettlementPreview {
    private static final BlockPos CENTER = new BlockPos(976,65,40);
    private static final AABB AREA = new AABB(952,62,16,1001,84,65);
    static void command(MinecraftServer server, JsonObject request) {
        var level = server.overworld();
        if (!request.get("command").getAsString().equals("settlement-setup")) throw new IllegalArgumentException("Unknown settlement preview operation");
        var preset = SettlementSpawner.Preset.valueOf(request.get("kind").getAsString().toUpperCase(java.util.Locale.ROOT));
        for (int x=59; x<=62; x++) for (int z=1; z<=4; z++) level.setChunkForced(x,z,true);
        level.getGameRules().getRule(GameRules.RULE_DOMOBSPAWNING).set(false,server);
        level.getGameRules().getRule(GameRules.RULE_DAYLIGHT).set(false,server);
        level.setDayTime(6000); level.setWeatherParameters(6000,0,false,false);
        level.getEntitiesOfClass(Entity.class, AREA, e -> e instanceof YukkuriEntity || e instanceof ItemEntity).forEach(Entity::discard);
        for (int x=952; x<=1000; x++) for (int z=16; z<=64; z++) {
            level.setBlockAndUpdate(new BlockPos(x,64,z),Blocks.GRASS_BLOCK.defaultBlockState());
            for (int y=65; y<89; y++) level.setBlockAndUpdate(new BlockPos(x,y,z),Blocks.AIR.defaultBlockState());
        }
        boolean openPit=request.has("terrain")&&request.get("terrain").getAsString().equals("pit");
        if(openPit) {
            for(int dx=-1;dx<=1;dx++)for(int dz=-3;dz<=-1;dz++) {
                var floor=CENTER.offset(dx,-1,dz);
                level.setBlockAndUpdate(floor.below(),Blocks.DIRT.defaultBlockState());
                level.setBlockAndUpdate(floor,Blocks.AIR.defaultBlockState());
            }
        } else if(preset==SettlementSpawner.Preset.FAMILY||preset==SettlementSpawner.Preset.WANDERER) {
            var mouth=CENTER.north(2);
            // An irregular pre-existing hillside is part of the test scene, not generated by any resident.
            for(int dx=-8;dx<=8;dx++)for(int depth=-1;depth<=12;depth++) {
                double ridge=4.5-Math.abs(dx)*.42-Math.abs(depth-5)*.28;
                int height=(int)Math.floor(ridge+Math.sin(dx*1.7+depth*.8)*.65);
                if(depth<0)height=Math.max(0,height-2);
                for(int y=0;y<height;y++)level.setBlockAndUpdate(mouth.offset(dx,y,-depth),
                        (y==height-1?Blocks.GRASS_BLOCK:y<2?Blocks.DIRT:Blocks.STONE).defaultBlockState());
            }
            NaturalShelterFixture.cave(level,mouth,net.minecraft.core.Direction.SOUTH);
        } else NaturalShelterFixture.region(level,CENTER);
        for (int trunkX : new int[]{958,976,994}) for (int trunkZ : new int[]{21,37,59}) {
            int ground=level.getHeight(net.minecraft.world.level.levelgen.Heightmap.Types.MOTION_BLOCKING,trunkX,trunkZ);
            if(openPit&&trunkX==976&&trunkZ==37)continue;
            for (int y=ground; y<=ground+7; y++) level.setBlockAndUpdate(new BlockPos(trunkX,y,trunkZ),Blocks.OAK_LOG.defaultBlockState());
            for (int dx=-5; dx<=5; dx++) for (int dz=-5; dz<=5; dz++) {
                int top = ground+(Math.abs(dx)+Math.abs(dz)>8?6:7);
                for (int y=ground+5; y<=top; y++) level.setBlockAndUpdate(new BlockPos(trunkX+dx,y,trunkZ+dz),
                        Blocks.OAK_LEAVES.defaultBlockState().setValue(LeavesBlock.PERSISTENT,true));
            }
        }
        for (int i=0; i<10; i++) {
            var grass=new BlockPos(970+i,65,43+(i%3));
            if(level.getBlockState(grass).isAir())level.setBlockAndUpdate(grass,Blocks.SHORT_GRASS.defaultBlockState());
        }
        for (var player : server.getPlayerList().getPlayers()) {
            player.setGameMode(GameType.SPECTATOR);
            player.teleportTo(level,976.5,66.5,46.2,180,16);
        }
        // Newly forced chunks must first become entity ticking before the generated members can be queried.
        server.tell(new net.minecraft.server.TickTask(server.getTickCount()+2, () -> {
            level.getEntitiesOfClass(ItemEntity.class,AREA).forEach(Entity::discard);
            List<YukkuriEntity> members = SettlementSpawner.spawn(level,CENTER,preset);
            for (YukkuriEntity member : members) {
                member.setNoAi(true);
                float facing=member.habitat().shelter()==null?0:member.habitat().shelter().facing().toYRot();
                member.setYRot(facing); member.setYHeadRot(facing); member.yBodyRot=facing;
                member.addTag("settlement_preview");
            }
            P0Control.reply(request,!members.isEmpty(),Map.of("preset",preset.name(),"count",members.size(),"members",
                    members.stream().map(e->Map.of("id",e.getUUID().toString(),"species",e.getVariant().assetId(),"stage",e.family().stage().name(),
                            "group",e.settlement().groupId()==null?"none":e.settlement().groupId().toString(),
                            "mother",e.family().mother()==null?"none":e.family().mother().toString(),
                            "father",e.family().father()==null?"none":e.family().father().toString(),
                            "partner",e.family().partner()==null?"none":e.family().partner().toString(),
                            "home",e.habitat().shelter()==null?"none":e.habitat().shelter().getBlockPos().toShortString(),
                            "facing",e.habitat().shelter()==null?"none":e.habitat().shelter().facing().getName())).toList()));
        }));
    }
    private SettlementPreview() {}
}
