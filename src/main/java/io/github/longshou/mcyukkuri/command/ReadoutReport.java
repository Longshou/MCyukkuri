package io.github.longshou.mcyukkuri.command;

import com.google.gson.JsonArray;
import com.google.gson.JsonParser;
import com.mojang.brigadier.arguments.StringArgumentType;
import com.mojang.brigadier.context.ContextChain;
import com.mojang.brigadier.exceptions.CommandSyntaxException;
import io.github.longshou.mcyukkuri.network.ReadoutNetworking;
import io.github.longshou.mcyukkuri.network.ReadoutPayload;
import net.minecraft.commands.CommandResultCallback;
import net.minecraft.commands.CommandSource;
import net.minecraft.commands.CommandSourceStack;
import net.minecraft.commands.execution.ChainModifiers;
import net.minecraft.commands.execution.CommandQueueEntry;
import net.minecraft.commands.execution.CustomCommandExecutor;
import net.minecraft.commands.execution.ExecutionControl;
import net.minecraft.commands.execution.Frame;
import net.minecraft.network.chat.Component;
import net.minecraft.core.BlockPos;

/** Captures a nested command's queued branches before delivering the executing player's report. */
final class ReadoutReport extends CustomCommandExecutor.WithErrorHandling<CommandSourceStack>
        implements CustomCommandExecutor.CommandAdapter<CommandSourceStack> {
    static final ReadoutReport EXECUTOR = new ReadoutReport();

    @Override protected void runGuarded(CommandSourceStack source, ContextChain<CommandSourceStack> chain,
            ChainModifiers modifiers, ExecutionControl<CommandSourceStack> control) throws CommandSyntaxException {
        var player = source.getPlayerOrException();
        String command = StringArgumentType.getString(chain.getTopContext().copyFor(source), "command");
        var messages = new JsonArray();
        // Store serialized components immediately: command-owned mutable components cannot change the snapshot later.
        class Capture implements CommandSource {
            int chars = 2;
            boolean tooLarge;
            public void sendSystemMessage(Component message) {
                if (tooLarge) return;
                String json = Component.Serializer.toJson(message, source.registryAccess());
                if (json.length() + 1L > ReadoutPayload.MAX_REPORT_CHARS - chars) { tooLarge = true; return; }
                chars += json.length() + 1;
                messages.add(JsonParser.parseString(json));
            }
            public boolean acceptsSuccess() { return true; }
            public boolean acceptsFailure() { return true; }
            public boolean shouldInformAdmins() { return false; }
        }
        var capture = new Capture();
        capture.sendSystemMessage(Component.literal("试玩场读数快照"));
        capture.sendSystemMessage(Component.literal("观察者：" + player.getGameProfile().getName()
                + "\n维度：" + source.getLevel().dimension().location()
                + "\n位置：" + BlockPos.containing(source.getPosition()).toShortString()
                + "\n游戏 tick：" + source.getLevel().getGameTime()));
        capture.sendSystemMessage(Component.literal("命令：/" + command));
        var reading = new CommandSourceStack(capture, source.getPosition(), source.getRotation(), source.getLevel(),
                2, "playground", Component.literal("playground"), source.getServer(), player);
        int metadataCount = messages.size();
        control.queueNext((execution, parentFrame) -> {
            execution.incrementCost();
            // Even for a directly typed readout (parent depth 0), nested return/discard must not erase our finish.
            int childDepth = parentFrame.depth() + 1;
            var childFrame = new Frame(childDepth, CommandResultCallback.EMPTY, execution.frameControlForDepth(childDepth));
            execution.queueNext(new CommandQueueEntry<>(childFrame,
                    (nestedExecution, frame) -> source.getServer().getCommands().performPrefixedCommand(reading, command)));
            // ExecutionContext pushes commands generated by each entry ahead of this outer-frame tail, including
            // BuildContexts' fork continuations and functions. A result callback would finish on the first branch.
            execution.queueNext(new CommandQueueEntry<>(parentFrame, (completedExecution, frame) -> {
                if (!capture.tooLarge && messages.size() == metadataCount)
                    capture.sendSystemMessage(Component.literal("本次命令没有输出：可能未匹配目标、条件未满足、分支失败或执行被取消。"));
                boolean sent = !capture.tooLarge && ReadoutNetworking.send(player, messages.toString());
                if (!sent) player.sendSystemMessage(Component.literal("读数报告过大，未显示不完整内容；请缩小目标范围后重试。"));
                source.callback().onResult(sent, sent ? 1 : 0);
                if (modifiers.isReturn()) {
                    if (sent) frame.returnSuccess(1); else frame.returnFailure();
                    frame.discard();
                }
            }));
        });
    }

    private ReadoutReport() {}
}
