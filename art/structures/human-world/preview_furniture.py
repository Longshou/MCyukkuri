def layouts(source_dir):
    """The village pet-shop lot, the street stall and the oni-san shop as generated by the modules in source_dir."""
    out = subprocess.run([sys.executable, '-c', DUMP, str(source_dir)], check=True, capture_output=True, text=True, cwd=source_dir).stdout
    return {k: {(x, y, z): (n, pr) for x, y, z, n, pr in v} for k, v in json.loads(out).items()}


def old_sources(ref, into):
    into.mkdir(parents=True, exist_ok=True)
    for name in SOURCES:
        shown = subprocess.run(['git', '-C', str(ROOT), 'show', f'{ref}:art/structures/human-world/{name}'], capture_output=True)
        if shown.returncode == 0: (into / name).write_bytes(shown.stdout)
    joined_source = subprocess.run(['git', '-C', str(ROOT), 'show', f'{ref}:scripts/furniture_placement.py'], capture_output=True)
    if joined_source.returncode == 0: (into / 'furniture_placement.py').write_bytes(joined_source.stdout)
    # The old build reads OUT only when saving; nothing is written here.
    return into


OPAQUE = ('planks', 'cobblestone', 'stone_bricks', 'log', 'wood', 'wool', 'terracotta', 'concrete', 'quartz', 'andesite', 'gravel',
          'grass_block', 'dirt', 'mud_bricks', 'barrel', 'hay_block', 'bookshelf', 'glass')


def opaque(n): return any(s in n for s in OPAQUE) and not n.endswith(('_slab', '_stairs', '_fence', '_wall', '_pane', '_trapdoor', '_door'))


def region_mesh(a, blocks, box, origin):
    """Visible blocks inside box ((x0, y0, z0), (x1, y1, z1)), moved so that origin is at 0."""
    (x0, y0, z0), (x1, y1, z1) = box
    keep = {p: v for p, v in blocks.items() if x0 <= p[0] <= x1 and y0 <= p[1] <= y1 and z0 <= p[2] <= z1}
    out = []
    for pos, (name, props) in keep.items():
        if name in ('minecraft:jigsaw', 'minecraft:air'): continue
        if opaque(name) and all(opaque(keep.get(tuple(pos[i] + d[i] for i in range(3)), ('air', {}))[0]) for d, _ in ps.FACES.values()):
            continue
        v = a.block(name, tuple(sorted(props.items()))).copy()
        if not len(v): continue
        v[:, :3] += np.array(pos) - np.array(origin); out.append(v)
    return np.concatenate(out)


class Bodies:
    """Adult yukkuri at game scale (model units / units_per_block), their textures pasted into a free corner of the block atlas."""
    SLOTS = {'reimu': (1024, 1536), 'marisa': (1536, 1536)}

    def __init__(self, a):
        from preview import Posed
        corrections = json.loads((ps.ASSETS / 'mcyukkuri/yukkuri_presentation/motion_corrections.json').read_text(encoding='utf8'))
        self.meshes = {}
        for ident, (ux, uy) in self.SLOTS.items():
            posed = Posed(ident, corrections); tri, uv, n = posed.frame('idle', 0)
            unit = posed.model['units_per_block']
            texture = Image.fromarray(posed.texture('neutral')).resize((512, 512), Image.Resampling.NEAREST)
            a.atlas.paste(texture, (ux, uy))
            uv = uv.reshape(-1, 2) * (512 / 2048) + np.array([ux, uy]) / 2048
            self.meshes[ident] = np.c_[tri.reshape(-1, 3) / unit, uv, np.repeat(n, 3, axis=0)]

    def at(self, ident, x, y, z, yaw=0.):
        v = self.meshes[ident].copy(); c, s = np.cos(np.radians(yaw)), np.sin(np.radians(yaw))
        turn = np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])
        v[:, :3] = v[:, :3] @ turn.T + [x, y, z]; v[:, 5:8] = v[:, 5:8] @ turn.T
        return v


def shot(a, vertices, out, name, view):
    width, height, az, el, span, center = view
    return ps.render(a, vertices, out, name, width, height, az, el, span, center).convert('RGB')


def pair(a, out, name, before, after, view, title, note):
    """Old and new at the same camera, side by side, with a caption."""
    left, right = shot(a, before, out, name + '-before', view), shot(a, after, out, name + '-after', view)
    w, h = left.size
    sheet = Image.new('RGB', (w * 2 + 30, h + 136), '#edf1eb'); d = ImageDraw.Draw(sheet)
    sheet.paste(left, (0, 136)); sheet.paste(right, (w + 30, 136))
    d.text((20, 10), title, font=ps.font(28), fill='#273e37'); d.text((20, 52), note, font=ps.font(17), fill='#596f65')
    d.text((20, 100), '原来', font=ps.font(22), fill='#8a3b2b'); d.text((w + 50, 100), '现在', font=ps.font(22), fill='#2b6a3b')
    sheet.save(out / f'{name}.png')
    for side in ('before', 'after'): (out / f'{name}-{side}.png').unlink()
    return name + '.png'


def floor(blocks, x0, x1, z0, z1, y, name):
    for x in range(x0, x1 + 1):
        for z in range(z0, z1 + 1): blocks[x, y, z] = (name, {})


def house_mock(new):
    """The museum house's table (museum_fields.House): oak floor, the table between two seats, a hanging lantern above."""
    b = {}; floor(b, -3, 3, -2, 2, -1, 'minecraft:oak_planks')
    for x in range(-3, 4): b[x, 0, -2] = b[x, 1, -2] = ('minecraft:oak_planks', {})
    if new:
        for (x, z), p in joined('wooden_table', [(0, 0)]).items(): b[x, 0, z] = ('mcyukkuri:wooden_table', p)
        for cx in (-1, 1):
            for (x, z), p in joined('wooden_bench', [(cx, 0)], 'z').items(): b[x, 0, z] = ('mcyukkuri:wooden_bench', p)
    else:
        b[0, 0, 0] = ('minecraft:oak_fence', {}); b[0, 1, 0] = ('minecraft:oak_pressure_plate', {'powered': 'false'})
        b[-1, 0, 0] = ('minecraft:oak_stairs', {'facing': 'east', 'half': 'bottom', 'shape': 'straight'})
        b[1, 0, 0] = ('minecraft:oak_stairs', {'facing': 'west', 'half': 'bottom', 'shape': 'straight'})
    return b


def closeup(new):
    """A lone stool, a three-piece bench and a 2x2 table on grass."""
    b = {}; floor(b, -4, 4, -3, 3, -1, 'minecraft:grass_block')
    if new:
        for cells, axis, kind in [([(-3, -1)], 'x', 'wooden_bench'), ([(-1, -1), (0, -1), (1, -1)], 'x', 'wooden_bench'),
                                  ([(-1, 1), (0, 1), (-1, 2), (0, 2)], 'x', 'wooden_table')]:
            for (x, z), p in joined(kind, cells, axis).items(): b[x, 0, z] = ('mcyukkuri:' + kind, p)
    else:
        stair = lambda f: ('minecraft:oak_stairs', {'facing': f, 'half': 'bottom', 'shape': 'straight'})
        b[-3, 0, -1] = stair('north'); b[-1, 0, -1] = stair('north'); b[0, 0, -1] = ('minecraft:oak_slab', {'type': 'bottom'}); b[1, 0, -1] = stair('north')
        for x, z in [(-1, 1), (0, 1), (-1, 2), (0, 2)]: b[x, 0, z] = ('minecraft:oak_fence', {}); b[x, 1, z] = ('minecraft:oak_pressure_plate', {})
    return b


